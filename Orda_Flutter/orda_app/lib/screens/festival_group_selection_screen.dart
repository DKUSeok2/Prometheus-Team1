  void _onNameChanged(String name) {
    setState(() {
      if (_userData.containsKey(name)) {
        _selectedPersonality = _userData[name]!['personality'];
        _selectedTravelStyle = _userData[name]!['travel_style'];
      } else {
        _selectedPersonality = null;
        _selectedTravelStyle = null;
      }
    });
  }

  void _startChatting() {
    final name = _nameController.text.trim();
    if (name.isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('이름을 입력해주세요.')),
      );
      return;
    }

    if (!_userData.containsKey(name)) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('등록되지 않은 이름입니다. 데모 참가자 이름을 입력해주세요.')),
      );
      return;
    }

    // 여행일정 데이터 가져오기
    final travelPlan = _userData[name]!['travel_plan'];
    
    // TravelPlanLoadingScreen으로 이동 (로딩 후 마크다운 페이지)
    Navigator.push(
      context,
      MaterialPageRoute(
        builder: (context) => TravelPlanLoadingScreen(
          userName: name,
          personality: _selectedPersonality!,
          travelStyle: _selectedTravelStyle!,
          travelPlan: travelPlan!, // 미리 정해진 여행일정 전달
        ),
      ),
    );
  }

